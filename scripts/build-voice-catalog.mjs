// Regenerates lib/cloud-languages.js from Microsoft's live voice list.
//
// Run with `node scripts/build-voice-catalog.mjs`. Voice names are not stable
// forever — Microsoft retired Davis, Tony, and Sara out from under us — so the
// catalog is generated rather than hand-maintained, and re-running this is the
// fix when a voice disappears.
//
// The language set tracks the languages YouTube's automatic dubbing covers, so
// a transcript pulled from a video always has a voice that can read it back.
import { writeFileSync } from 'node:fs';
import { EdgeTTS } from '@andresaya/edge-tts';

// Preferred locale per language. Where a language spans several countries the
// choice is the largest audience, not the alphabetically first locale.
const TARGET_LOCALES = [
  ['Arabic', 'ar-EG'],
  ['Bengali', 'bn-IN'],
  ['Chinese', 'zh-CN'],
  ['Chinese (Traditional)', 'zh-TW'],
  ['Dutch', 'nl-NL'],
  ['Farsi', 'fa-IR'],
  ['French', 'fr-FR'],
  ['German', 'de-DE'],
  ['Hebrew', 'he-IL'],
  ['Hindi', 'hi-IN'],
  ['Indonesian', 'id-ID'],
  ['Italian', 'it-IT'],
  ['Japanese', 'ja-JP'],
  ['Korean', 'ko-KR'],
  ['Malayalam', 'ml-IN'],
  ['Polish', 'pl-PL'],
  ['Portuguese', 'pt-BR'],
  ['Punjabi', 'pa-IN'],
  ['Romanian', 'ro-RO'],
  ['Russian', 'ru-RU'],
  ['Spanish', 'es-ES'],
  ['Swahili', 'sw-KE'],
  ['Tamil', 'ta-IN'],
  ['Telugu', 'te-IN'],
  ['Thai', 'th-TH'],
  ['Turkish', 'tr-TR'],
  ['Ukrainian', 'uk-UA'],
  ['Urdu', 'ur-PK'],
  ['Vietnamese', 'vi-VN'],
];

function pick(voices, locale, gender) {
  return voices.find((v) => v.Locale === locale && v.Gender === gender);
}

// Trims "Spanish (Spain)" down to "Spain", which is the only part the language
// heading is not already saying.
function regionOf(localeName) {
  const match = /\(([^)]+)\)/.exec(localeName);
  return match ? match[1] : localeName;
}

const tts = new EdgeTTS();
const voices = await tts.getVoices();

const catalog = [];
const missing = [];

for (const [language, locale] of TARGET_LOCALES) {
  const female = pick(voices, locale, 'Female');
  const male = pick(voices, locale, 'Male');

  if (!female && !male) {
    // Locale absent entirely: fall back to any locale sharing the language tag.
    const tag = locale.split('-')[0];
    const anyLocale = voices.find((v) => v.Locale.startsWith(`${tag}-`));
    if (!anyLocale) {
      missing.push(`${language} (${locale})`);
      continue;
    }
    missing.push(`${language}: ${locale} unavailable, ${anyLocale.Locale} exists`);
    continue;
  }

  const entries = [];
  for (const voice of [female, male]) {
    if (!voice) continue;
    entries.push({
      id: voice.ShortName,
      name: voice.DisplayName,
      desc: `${voice.Gender}, ${regionOf(voice.LocaleName)}`,
    });
  }
  catalog.push({ language, voices: entries });
}

const body = catalog
  .map(
    ({ language, voices }) =>
      `  {\n    language: '${language}',\n    voices: [\n` +
      voices
        .map((v) => `      { id: '${v.id}', name: '${v.name}', desc: '${v.desc}' },`)
        .join('\n') +
      `\n    ],\n  },`,
  )
  .join('\n');

const file = `// Generated by scripts/build-voice-catalog.mjs — do not edit by hand.
//
// Cloud voices for the languages YouTube's automatic dubbing covers, so any
// transcript taken from a video has a voice able to read it back. English is
// not here; it keeps its own curated list in the reader.
//
// Microsoft has no Punjabi neural voice, so that one language of YouTube's set
// cannot be offered on the cloud tier.

export const CLOUD_LANGUAGES = [
${body}
];

export const CLOUD_LANGUAGE_NAMES = CLOUD_LANGUAGES.map((entry) => entry.language);

export function voicesForLanguage(language) {
  return CLOUD_LANGUAGES.find((entry) => entry.language === language)?.voices ?? [];
}
`;

writeFileSync(new URL('../lib/cloud-languages.js', import.meta.url), file);

const total = catalog.reduce((n, entry) => n + entry.voices.length, 0);
console.log(`wrote lib/cloud-languages.js`);
console.log(`  languages requested: ${TARGET_LOCALES.length}`);
console.log(`  languages filled:    ${catalog.length}`);
console.log(`  voices:              ${total}`);
if (missing.length) {
  console.log(`\nunfilled:\n  ${missing.join('\n  ')}`);
}
